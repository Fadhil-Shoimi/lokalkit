// Git in the LokalKit terminal.
//
// cmd.exe cannot run anything when it draws its prompt, so on its own it
// cannot show the current git branch. Two layers:
//
//   - Always: lk-prompt.cmd works out the branch and status and sets PROMPT.
//     It runs when the terminal opens and after every git / cd / pushd /
//     popd (doskey macros), which is when the branch can change.
//   - With Clink installed (Install tab): Clink adds a Lua prompt that is
//     redrawn on every Enter, Tab completion for git branches and remotes,
//     saved history, Ctrl+R search and suggestions.

// TerminalExtras are the optional parts of the terminal init script.
type TerminalExtras struct {
	PromptScript string // path of lk-prompt.cmd (used without Clink)
	ClinkExe     string // clink_x64.exe, "" = not installed
	ClinkProfile string // folder with the LokalKit Clink scripts and settings
}

// Prompt colours (24-bit), shared by the cmd and Clink prompts.
const (
	promptYellow = "38;2;250;204;21"
	promptGrey   = "38;2;148;156;171"
	promptGreen  = "38;2;52;197;106"
	promptOrange = "38;2;251;146;60"
	promptRed    = "38;2;240;99;99"
)

// basePrompt is the prompt without git: "● C:\folder" then "❯ ".
const basePrompt = "$E[" + promptYellow + "m●$E[0m $E[" + promptGrey + "m$P$E[0m$_$E[" + promptYellow + "m❯$E[0m "

// gitAliases are short git commands, shown in the banner.
var gitAliases = []struct{ name, cmd string }{
	{"gs", "git status $*"},
	{"gl", "git log --oneline --graph --decorate -20 $*"},
	{"gd", "git diff $*"},
	{"gco", "git checkout $*"},
	{"gp", "git push $*"},
	{"gpl", "git pull $*"},
}

// BuildPromptScript is lk-prompt.cmd: it sets PROMPT to show the git branch,
// uncommitted changes (●3 or ✓), commits to push/pull (↑1 ↓2) and branches
// that were never pushed.
func BuildPromptScript() string {
	var b strings.Builder
	w := func(s string) { b.WriteString(s + "\r\n") }
	w("@echo off")
	w(`set "LK_B=" & set "LK_D=" & set "LK_A=" & set "LK_H=" & set "LK_U="`)
	w(`for /f "delims=" %%i in ('git branch --show-current 2^>nul') do set "LK_B=%%i"`)
	w(`if not defined LK_B for /f "delims=" %%i in ('git rev-parse --short HEAD 2^>nul') do set "LK_B=(%%i)"`)
	w(`if not defined LK_B goto nogit`)
	w(`for /f %%i in ('git --no-optional-locks status --porcelain 2^>nul ^| find /c /v ""') do set "LK_D=%%i"`)
	w(`for /f "delims=" %%i in ('git rev-parse --abbrev-ref --symbolic-full-name @{u} 2^>nul') do set "LK_U=%%i"`)
	w(`if defined LK_U for /f "tokens=1,2" %%a in ('git rev-list --left-right --count @{u}...HEAD 2^>nul') do set "LK_H=%%a" & set "LK_A=%%b"`)
	// "$" starts a prompt code, so a "$" in a branch name is doubled.
	w(`set "LK_B=%LK_B:$=$$%"`)
	w(`set "LK_S= $E[` + promptGreen + `m✓"`)
	w(`if not "%LK_D%"=="0" set "LK_S= $E[` + promptOrange + `m●%LK_D%"`)
	w(`if defined LK_A if not "%LK_A%"=="0" set "LK_S=%LK_S% $E[` + promptYellow + `m↑%LK_A%"`)
	w(`if defined LK_H if not "%LK_H%"=="0" set "LK_S=%LK_S% $E[` + promptYellow + `m↓%LK_H%"`)
	w(`if not defined LK_U set "LK_S=%LK_S% $E[` + promptGrey + `m(not pushed)"`)
	w(`set "PROMPT=$E[` + promptYellow + `m●$E[0m $E[` + promptGrey + `m$P$E[0m  $E[` + promptGrey + `mgit:($E[` + promptGreen + `m%LK_B%$E[` + promptGrey + `m)$E[0m%LK_S%$E[0m$_$E[` + promptYellow + `m❯$E[0m "`)
	w(`goto done`)
	w(`:nogit`)
	w(`set "PROMPT=` + basePrompt + `"`)
	w(`:done`)
	w(`set "LK_B=" & set "LK_D=" & set "LK_A=" & set "LK_H=" & set "LK_U=" & set "LK_S="`)
	return b.String()
}


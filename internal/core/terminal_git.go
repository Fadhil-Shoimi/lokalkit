// ClinkLua is the LokalKit prompt and git completion for Clink.
const ClinkLua = `-- Generated by LokalKit. Your own Clink scripts can go next to this file.

local Y  = "\x1b[` + promptYellow + `m"
local M  = "\x1b[` + promptGrey + `m"
local GR = "\x1b[` + promptGreen + `m"
local OR = "\x1b[` + promptOrange + `m"
local RD = "\x1b[` + promptRed + `m"
local N  = "\x1b[0m"

local function lines(cmd)
  local out = {}
  -- Inside the prompt coroutine, io.popenyield lets Clink keep the prompt
  -- responsive while git runs.
  local _, main = coroutine.running()
  local popen = (not main and io.popenyield) or io.popen
  local f = popen(cmd .. " 2>nul")
  if f then
    for l in f:lines() do
      if l ~= "" then table.insert(out, l) end
    end
    f:close()
  end
  return out
end

-- Branch status from "git status --branch": changes, ahead/behind, upstream.
local function git_status()
  local info = { dirty = 0, ahead = 0, behind = 0, upstream = false }
  for _, l in ipairs(lines("git --no-optional-locks status --porcelain=v1 --branch")) do
    if l:sub(1, 2) == "##" then
      info.ahead = tonumber(l:match("ahead (%d+)")) or 0
      info.behind = tonumber(l:match("behind (%d+)")) or 0
      info.upstream = l:find("%.%.%.") ~= nil
    else
      info.dirty = info.dirty + 1
    end
  end
  return info
end

local function current_branch()
  local b = git.getbranch and git.getbranch()
  if b and b ~= "" then return b end
  local sha = lines("git rev-parse --short HEAD")[1]
  return sha and ("(" .. sha .. ")") or "?"
end

local lokalkit = clink.promptfilter(10)
function lokalkit:filter()
  local line = Y .. "●" .. N .. " " .. M .. os.getcwd() .. N
  if git.getgitdir and git.getgitdir() then
    line = line .. "  " .. M .. "git:(" .. GR .. current_branch() .. M .. ")" .. N
    local action = git.getaction and git.getaction()
    if action then line = line .. " " .. RD .. string.upper(action) .. N end
    -- Status runs in the background so the prompt never waits for it.
    local st = clink.promptcoroutine and clink.promptcoroutine(git_status) or git_status()
    if st then
      if st.dirty > 0 then line = line .. " " .. OR .. "●" .. st.dirty .. N
      else line = line .. " " .. GR .. "✓" .. N end
      if st.ahead > 0 then line = line .. " " .. Y .. "↑" .. st.ahead .. N end
      if st.behind > 0 then line = line .. " " .. Y .. "↓" .. st.behind .. N end
      if not st.upstream then line = line .. " " .. M .. "(not pushed)" .. N end
    end
  end
  return line .. "\r\n" .. Y .. "❯" .. N .. " ", false
end

-- Tab completion: branches (local, and remote ones without "origin/") and remotes.
local function branches()
  local seen, out = {}, {}
  local function add(b)
    if b ~= "" and not seen[b] then seen[b] = true; table.insert(out, b) end
  end
  for _, l in ipairs(lines("git branch --list")) do
    local b = l:gsub("^[%*%+]?%s*", "")
    if not b:find("^%(") then add(b) end
  end
  for _, l in ipairs(lines("git branch -r")) do
    local b = l:gsub("^%s*", "")
    if not b:find("->", 1, true) then add((b:gsub("^[^/]+/", ""))) end
  end
  return out
end

local function remotes() return lines("git remote") end

local br = clink.argmatcher():addarg({ branches })
local remote_branch = clink.argmatcher():addarg({ remotes }):addarg({ branches })

clink.argmatcher("git"):addarg({
  "add", "bisect", "blame", "branch" .. br, "checkout" .. br, "cherry-pick", "clean", "clone",
  "commit", "config", "diff" .. br, "fetch" .. clink.argmatcher():addarg({ remotes }), "init",
  "log" .. br, "merge" .. br, "mv", "pull" .. remote_branch, "push" .. remote_branch,
  "rebase" .. br, "remote", "reset", "restore", "revert", "rm", "show", "stash", "status",
  "switch" .. br, "tag",
})
`

// clinkExe finds clink_x64.exe installed from the Install tab.
func (m *Manager) clinkExe() string {
	return findUnder(filepath.Join(m.P.Bin, "clink"), "clink_x64.exe")
}

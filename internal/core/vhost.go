type Project struct {
	Name        string `json:"name"`
	Path        string `json:"path"`
	DocRoot     string `json:"docRoot"`
	Host        string `json:"host"`
	URL         string `json:"url"`
	HTTPS       string `json:"https"` // https URL when HTTPS is enabled
	Kind        string `json:"kind"`  // laravel, wordpress, php
	Task        string `json:"task"`  // set while Composer/Laravel setup runs
	Error       string `json:"error"` // last Composer/Laravel setup error
	NeedsDeps   bool   `json:"needsDeps"`
	NeedsAssets bool   `json:"needsAssets"` // starter kit front-end not built yet // composer.json but no vendor/ (e.g. an interrupted install)
}

var hostLabelRe = regexp.MustCompile(`^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$`)

// HostLabel turns a folder name into a valid domain label ("My_App" -> "my-app").
func HostLabel(name string) string {
	s := strings.ToLower(strings.TrimSpace(name))
	s = strings.NewReplacer(" ", "-", "_", "-", ".", "-").Replace(s)
	if !hostLabelRe.MatchString(s) {
		return ""
	}
	return s
}

// Projects lists every folder in www that can become a virtual host.
func (m *Manager) Projects() []Project {
	return m.annotate(ScanProjects(m.P.WWW, m.config()))
}

func ScanProjects(www string, cfg Config) []Project {
	entries, err := os.ReadDir(www)
	if err != nil {
		return nil
	}
	var out []Project
	for _, e := range entries {
		if !e.IsDir() || strings.HasPrefix(e.Name(), ".") {
			continue
		}
		label := HostLabel(e.Name())
		if label == "" {
			continue
		}
		dir := filepath.Join(www, e.Name())
		p := Project{Name: e.Name(), Path: dir, DocRoot: dir, Host: label + "." + cfg.TLD, Kind: "php"}
		if isDir(filepath.Join(dir, "public")) {
			p.DocRoot = filepath.Join(dir, "public")
		}
		switch {
		case exists(filepath.Join(dir, "artisan")):
			p.Kind = "laravel"
		case exists(filepath.Join(dir, "wp-config.php")) || exists(filepath.Join(dir, "wp-login.php")):
			p.Kind = "wordpress"
		}
		p.URL = "http://" + p.Host
		if cfg.ApachePort != 80 {
			p.URL += fmt.Sprintf(":%d", cfg.ApachePort)
		}
		if cfg.SSL {
			p.HTTPS = "https://" + p.Host
			if cfg.SSLPort != 443 {
				p.HTTPS += fmt.Sprintf(":%d", cfg.SSLPort)
			}
		}
		out = append(out, p)
	}
	return out
}

func BuildVhost(p Project, port int) string {
	dr := slash(p.DocRoot)
	return fmt.Sprintf(`# Generated by LokalKit for %s
<VirtualHost *:%d>
    ServerName %s
    ServerAlias *.%s
    DocumentRoot "%s"
    <Directory "%s">
        Options Indexes FollowSymLinks
        AllowOverride All
        Require all granted
    </Directory>
</VirtualHost>
`, p.Name, port, p.Host, p.Host, dr, dr)
}

// BuildSSLVhost is the HTTPS twin of BuildVhost.
func BuildSSLVhost(p Project, ssl SSLFiles) string {
	dr := slash(p.DocRoot)
	return fmt.Sprintf(`# Generated by LokalKit for %s (HTTPS)
<VirtualHost *:%d>
    ServerName %s
    ServerAlias *.%s
    DocumentRoot "%s"
    SSLEngine on
    SSLCertificateFile "%s"
    SSLCertificateKeyFile "%s"
    <Directory "%s">
        Options Indexes FollowSymLinks
        AllowOverride All
        Require all granted
    </Directory>
</VirtualHost>
`, p.Name, ssl.Port, p.Host, p.Host, dr, slash(ssl.Cert), slash(ssl.Key), dr)
}

// WriteVhosts regenerates etc/apache/sites-enabled/auto.*.conf.
// ssl is nil when HTTPS is off (or unavailable this run).
func (m *Manager) WriteVhosts(ssl *SSLFiles) error {
	dir := filepath.Join(m.P.Etc, "apache", "sites-enabled")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	old, _ := filepath.Glob(filepath.Join(dir, "auto.*.conf"))
	for _, f := range old {
		_ = os.Remove(f)
	}
	cfg := m.config()
	def := fmt.Sprintf("# Generated by LokalKit\n<VirtualHost *:%d>\n    ServerName localhost\n    DocumentRoot \"%s\"\n</VirtualHost>\n",
		cfg.ApachePort, slash(m.P.WWW))
	if ssl != nil {
		def += BuildSSLVhost(Project{Name: "localhost", Host: "localhost", DocRoot: m.P.WWW}, *ssl)
		def = strings.Replace(def, "    ServerAlias *.localhost\n", "", 1)
	}
	if err := os.WriteFile(filepath.Join(dir, "auto.000-localhost.conf"), []byte(def), 0o644); err != nil {
		return err
	}
	if ad := m.adminerDir(); exists(filepath.Join(ad, "index.php")) {
		alias := fmt.Sprintf("# Adminer: http://localhost/adminer/\nAlias /adminer \"%s\"\n<Directory \"%s\">\n    Require local\n    DirectoryIndex index.php\n</Directory>\n", slash(ad), slash(ad))
		if err := os.WriteFile(filepath.Join(dir, "auto.001-adminer.conf"), []byte(alias), 0o644); err != nil {
			return err
		}
	}
	if !cfg.AutoVhost {
		return nil
	}
	for _, p := range m.Projects() {
		conf := BuildVhost(p, cfg.ApachePort)
		if ssl != nil {
			conf += "\n" + BuildSSLVhost(p, *ssl)
		}
		if err := os.WriteFile(filepath.Join(dir, "auto."+p.Host+".conf"), []byte(conf), 0o644); err != nil {
			return err
		}
	}
	return nil
}

const (
	hostsBegin = "# >>> LokalKit (auto-generated, do not edit this block)"
	hostsEnd   = "# <<< LokalKit"
)

// hostsPathOverride lets tests point at a temporary hosts file.
var hostsPathOverride string

func HostsFilePath() string {
	if hostsPathOverride != "" {
		return hostsPathOverride
	}
	if runtime.GOOS == "windows" {
		root := os.Getenv("SystemRoot")
		if root == "" {
			root = `C:\Windows`
		}
		return filepath.Join(root, "System32", "drivers", "etc", "hosts")
	}
	return "/etc/hosts"
}

// BuildHostsFile replaces the LokalKit block in a hosts file with entries for hosts.
func BuildHostsFile(current string, hosts []string) string {
	nl := "\n"
	if strings.Contains(current, "\r\n") {
		nl = "\r\n"
	}
	lines := strings.Split(strings.ReplaceAll(current, "\r\n", "\n"), "\n")
	var kept []string
	inBlock := false
	for _, l := range lines {
		t := strings.TrimSpace(l)
		if t == hostsBegin {
			inBlock = true
			continue
		}
		if inBlock {
			if t == hostsEnd {
				inBlock = false
			}
			continue
		}
		kept = append(kept, l)
	}
	for len(kept) > 0 && strings.TrimSpace(kept[len(kept)-1]) == "" {
		kept = kept[:len(kept)-1]
	}
	if len(kept) == 0 && len(hosts) == 0 {
		return ""
	}
	if len(hosts) > 0 {
		kept = append(kept, "", hostsBegin)
		for _, h := range hosts {
			kept = append(kept, "127.0.0.1 "+h)
		}
		kept = append(kept, hostsEnd)
	}
	return strings.Join(kept, nl) + nl
}

var ErrNeedAdmin = errors.New("admin rights are needed to edit the hosts file")

// SyncHostsFile writes the hosts file. Returns changed=false when already up to date.
func SyncHostsFile(hosts []string) (changed bool, err error) {
	path := HostsFilePath()
	cur, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return false, err
	}
	want := BuildHostsFile(string(cur), hosts)
	if want == string(cur) {
		return false, nil
	}
	if err := writeHostsFile(path, []byte(want)); err != nil {
		if errors.Is(err, fs.ErrPermission) && !processElevated() {
			return true, ErrNeedAdmin
		}
		return true, errors.New(describeHostsWriteError(err))
	}
	return true, nil
}

// UsesLocalhostTLD: browsers resolve *.localhost to this computer by
// themselves, so no hosts file entries (and no admin prompt) are needed.
func (m *Manager) UsesLocalhostTLD() bool { return m.config().TLD == "localhost" }

// hostNames are the names that need a hosts file entry.
func (m *Manager) hostNames() []string {
	if m.UsesLocalhostTLD() {
		return nil
	}
	return m.projectHosts()
}

// projectHosts are all project domains (for vhosts and the certificate).
func (m *Manager) projectHosts() []string {
	if !m.config().AutoVhost {
		return nil
	}
	var hs []string
	for _, p := range m.Projects() {
		hs = append(hs, p.Host)
	}
	return hs
}

// SyncHosts updates the hosts file, asking Windows for admin rights (UAC)
// only when something actually changed.
func (m *Manager) SyncHosts() error {
	if m.UsesLocalhostTLD() {
		return nil // browsers resolve *.localhost themselves; leave the hosts file alone
	}
	changed, err := SyncHostsFile(m.hostNames())
	if err == nil {
		if changed {
			flushDNS()
			m.Logf("info", "Hosts file updated")
		}
		return nil
	}
	if !errors.Is(err, ErrNeedAdmin) || runtime.GOOS != "windows" {
		return fmt.Errorf("cannot update the hosts file: %w", err)
	}
	m.Logf("info", "Asking for admin rights to update the hosts file (approve the Windows prompt)...")
	helperLog := filepath.Join(m.P.Logs, "hosts-helper.log")
	_ = os.Remove(helperLog)
	exe, _ := os.Executable()
	runErr := runElevated(exe, []string{"--sync-hosts", m.P.Root})
	if still, _ := SyncHostsFile(m.hostNames()); !still {
		flushDNS()
		m.Logf("ok", "Hosts file updated")
		return nil
	}
	detail := strings.TrimSpace(readSmall(helperLog))
	if detail == "" && runErr != nil {
		detail = runErr.Error()
	}
	if detail == "" {
		detail = "unknown reason"
	}
	return fmt.Errorf("could not add your projects to the hosts file: %s. %s", detail, manualHostsHint)
}

const manualHostsHint = `Easiest fix: switch the domain to .localhost in Settings (no hosts file needed). Or add them by hand: open Notepad as administrator, open C:\Windows\System32\drivers\etc\hosts and add "127.0.0.1 project.test" for each project`

// MissingFromHosts returns project hosts that the hosts file does not map yet.
func (m *Manager) MissingFromHosts() []string {
	b, _ := os.ReadFile(HostsFilePath())
	have := map[string]bool{}
	for _, line := range strings.Split(string(b), "\n") {
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		f := strings.Fields(line)
		for _, h := range f[min(1, len(f)):] {
			have[strings.ToLower(h)] = true
		}
	}
	var missing []string
	for _, h := range m.hostNames() {
		if !have[h] {
			missing = append(missing, h)
		}
	}
	return missing
}

func readSmall(path string) string {
	b, err := os.ReadFile(path)
	if err != nil || len(b) > 4096 {
		return ""
	}
	return string(b)
}

// flushDNS clears Windows' DNS cache so a name that failed to resolve a
// moment ago ("NXDOMAIN") is looked up again in the new hosts file.
func flushDNS() {
	if runtime.GOOS != "windows" {
		return
	}
	cmd := exec.Command("ipconfig", "/flushdns")
	hideWindow(cmd)
	_ = cmd.Run()
}

// RunElevatedHostsSync is what "lokalkit.exe --sync-hosts <root>" runs as
// admin. Errors are also written to logs/hosts-helper.log for the main app.
func RunElevatedHostsSync(root string) (err error) {
	p := NewPaths(root)
	defer func() {
		if err != nil {
			_ = os.MkdirAll(p.Logs, 0o755)
			_ = os.WriteFile(filepath.Join(p.Logs, "hosts-helper.log"), []byte(err.Error()), 0o644)
		}
	}()
	cfg, err := LoadConfig(filepath.Join(root, "lokalkit.json"))
	if err != nil {
		return err
	}
	var hs []string
	if cfg.AutoVhost {
		for _, pr := range ScanProjects(p.WWW, cfg) {
			hs = append(hs, pr.Host)
		}
	}
	_, err = SyncHostsFile(hs)
	return err
}

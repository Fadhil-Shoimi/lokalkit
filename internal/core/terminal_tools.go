// Helpers for the LokalKit terminal: the project list behind "p" (and the
// Clink completion and automatic PHP switch), the batch commands in
// etc\terminal\bin and the lk-help text.

// BuildProjectsList is etc\terminal\projects.txt, one project per line:
// name|folder|PHP folder|PHP version|kind.
func (m *Manager) BuildProjectsList() string {
	var b strings.Builder
	for _, p := range m.Projects() {
		php, _, _, ok := m.ProjectPHPChoice(p.Name)
		if !ok {
			php = PHPInstall{}
		}
		fields := []string{p.Name, p.Path, php.Dir, php.Version, p.Kind}
		for i, f := range fields {
			if f == "" {
				fields[i] = "-" // for /f merges empty fields, so never leave one empty
			}
		}
		b.WriteString(strings.Join(fields, "|") + "\r\n")
	}
	return b.String()
}

// writeTerminalProjects refreshes projects.txt (called whenever virtual
// hosts are rewritten, so open terminals see new projects and PHP pins).
func (m *Manager) writeTerminalProjects() {
	dir := m.terminalDir()
	if err := os.MkdirAll(dir, 0o755); err == nil {
		_ = os.WriteFile(filepath.Join(dir, "projects.txt"), []byte(m.BuildProjectsList()), 0o644)
	}
}

// writeTerminalHelpers writes projects.txt, the bin\*.cmd commands and help.txt.
func (m *Manager) writeTerminalHelpers() error {
	dir := m.terminalDir()
	bin := filepath.Join(dir, "bin")
	if err := os.MkdirAll(bin, 0o755); err != nil {
		return err
	}
	m.writeTerminalProjects()
	for name, body := range map[string]string{
		"p.cmd":      ProjectJumpScript,
		"gac.cmd":    GitAddCommitScript,
		"gclean.cmd": GitCleanScript,
		"lk.cmd":     LKScript,
	} {
		if err := os.WriteFile(filepath.Join(bin, name), []byte(crlf(body)), 0o644); err != nil {
			return err
		}
	}
	return os.WriteFile(filepath.Join(dir, "help.txt"), []byte(crlf(TerminalHelp)), 0o644)
}

func crlf(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "\r\n", "\n"), "\n", "\r\n")
}


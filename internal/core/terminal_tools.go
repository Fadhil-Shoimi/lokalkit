// GitAddCommitScript is "gac message": git add -A, then commit with the
// message (quotes optional).
var GitAddCommitScript = `@echo off
rem Generated by LokalKit: gac <message> = git add -A + git commit -m <message>
if "%~1"=="" (echo Usage: gac your commit message& exit /b 1)
set "LK_MSG=%*"
set "LK_MSG=%LK_MSG:"=%"
git add -A && git commit -m "%LK_MSG%"
set "LK_MSG="
` + refreshPromptLine + `
`

// GitCleanScript is "gclean": deletes local branches already merged into
// the current one (never main, master, develop or the current branch).
var GitCleanScript = `@echo off
rem Generated by LokalKit: gclean deletes local branches that are already merged.
git rev-parse --git-dir >nul 2>nul || (echo Not a git repository.& exit /b 1)
set "LK_DEL=0"
for /f "tokens=1" %%a in ('git branch --merged 2^>nul') do if not "%%a"=="*" if not "%%a"=="+" if /i not "%%a"=="main" if /i not "%%a"=="master" if /i not "%%a"=="develop" (git branch -d %%a && set /a LK_DEL+=1 >nul)
if "%LK_DEL%"=="0" (echo No merged branches to delete.) else (echo Deleted %LK_DEL% merged branch^(es^).)
set "LK_DEL="
` + refreshPromptLine + `
`

// LKScript is "lk": it sends the command and the current folder to the
// running LokalKit (address and token in lk-api.txt) with Windows' curl.exe
// and prints the answer. If LokalKit is closed, it is started in the tray.
var LKScript = `@echo off
rem Generated by LokalKit: lk <command> controls LokalKit. Type lk help.
setlocal
set "LK_API=%~dp0..\lk-api.txt"
set "LK_TRIED="
:send
if not exist "%LK_API%" goto launch
set "LK_PORT=" & set "LK_TOKEN="
for /f "usebackq tokens=1,2" %%a in ("%LK_API%") do (set "LK_PORT=%%a" & set "LK_TOKEN=%%b")
curl.exe -s -X POST "http://127.0.0.1:%LK_PORT%/lk" -H "X-LK-Token: %LK_TOKEN%" --data-urlencode "dir=%CD%" --data-urlencode "args=%*"
if errorlevel 7 if not errorlevel 8 goto launch
exit /b %errorlevel%
:launch
if defined LK_TRIED (echo LokalKit did not answer. Open LokalKit and try again.& exit /b 1)
set "LK_TRIED=1"
if not defined LK_EXE (echo LokalKit is not running. Open LokalKit and try again.& exit /b 1)
if not exist "%LK_EXE%" (echo LokalKit is not running. Open LokalKit and try again.& exit /b 1)
echo Starting LokalKit in the tray...
del "%LK_API%" 2>nul
start "" "%LK_EXE%" --tray
for /l %%i in (1,1,30) do (if exist "%LK_API%" goto send) & ping -n 2 127.0.0.1 >nul
echo LokalKit did not start in time. Open it and try again.
exit /b 1
`

